// 评分：只统计已答题
export function quizScore(answers: (number | null)[]): { correct: number; total: number; rate: number } {
  const answered = ZIWEI_QUIZ.map((q, i) => ({ q, i })).filter(({ i }) => answers[i] !== null)
  const total = answered.length
  const correct = answered.filter(({ i, q }) => answers[i] === q.answer).length
  return { correct, total, rate: total > 0 ? Math.round((correct / total) * 100) : 0 }
}
