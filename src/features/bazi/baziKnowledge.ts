// 喜忌五行：以日主五行为中心，生我/同我者喜，克我/泄我者视强弱而定
export function yongShenDirection(dayWx: string, strong: '强' | '弱' | '中'): { xi: string; ji: string } {
  const sheng: Record<string, string> = { 木: '水', 火: '木', 土: '火', 金: '土', 水: '金' }
  const ke: Record<string, string> = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' }
  const xie: Record<string, string> = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' }
  if (strong === '强') {
    // 喜克泄耗：克我（官杀）、我生（食伤）、我克（财）
    return { xi: `${ke[dayWx]}（官杀） · ${xie[dayWx]}（食伤） · ${dayWx}克之五行（财）`, ji: `${sheng[dayWx]}（印） · ${dayWx}（比劫）` }
  }
  if (strong === '弱') {
    return { xi: `${sheng[dayWx]}（印） · ${dayWx}（比劫）`, ji: `${ke[dayWx]}（官杀） · ${xie[dayWx]}（食伤） · ${dayWx}克之五行（财）` }
  }
  return { xi: '调和流通为要，视格局取用', ji: '忌过强过弱之偏枯' }
}

